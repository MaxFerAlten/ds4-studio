#!/usr/bin/env node
// Generate generated/lean_orchestration_policy.h from the canonical policy JSON.
//
// The C orchestrator and the Node orchestrator must agree on the Lean proof
// budget. config/lean-orchestration-policy.json is the single source; this
// script is the only thing allowed to copy those numbers into C.

import { mkdirSync, readFileSync, writeFileSync } from "fs";
import { dirname, resolve } from "path";
import { fileURLToPath } from "url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const SOURCE = resolve(ROOT, "config/lean-orchestration-policy.json");
const TARGET = resolve(ROOT, "generated/lean_orchestration_policy.h");

const REQUIRED = [
  "version",
  "maxAttempts",
  "maxSameFailure",
  "maxPrematureFinalizations",
  "maxWallClockMs",
  "strategyChangeAfter",
];

const policy = JSON.parse(readFileSync(SOURCE, "utf8"));
for (const key of REQUIRED) {
  if (!Number.isInteger(policy[key])) {
    throw new Error(`${SOURCE}: '${key}' must be an integer, got ${policy[key]}`);
  }
}

const header = `/* Generated by scripts/generate-lean-orchestration-policy.mjs — do not edit.
 * Source: config/lean-orchestration-policy.json
 *
 * The native Lean turn orchestrator and the Node one share this budget. A
 * number that appears here must not be retyped anywhere else in C. */
#ifndef DS4_LEAN_ORCHESTRATION_POLICY_H
#define DS4_LEAN_ORCHESTRATION_POLICY_H

#define DS4_LEAN_POLICY_VERSION ${policy.version}
#define DS4_LEAN_MAX_ATTEMPTS ${policy.maxAttempts}
#define DS4_LEAN_MAX_SAME_FAILURE ${policy.maxSameFailure}
#define DS4_LEAN_MAX_PREMATURE_FINALIZATIONS ${policy.maxPrematureFinalizations}
#define DS4_LEAN_MAX_WALL_CLOCK_MS ${policy.maxWallClockMs}
#define DS4_LEAN_STRATEGY_CHANGE_AFTER ${policy.strategyChangeAfter}

#endif /* DS4_LEAN_ORCHESTRATION_POLICY_H */
`;

mkdirSync(dirname(TARGET), { recursive: true });
writeFileSync(TARGET, header);
process.stdout.write(`generated ${TARGET}\n`);
