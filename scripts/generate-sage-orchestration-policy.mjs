#!/usr/bin/env node
// Generate generated/sage_orchestration_policy.h from the canonical policy JSON.
//
// The native Sage mirror and the Node orchestrator must not carry two budgets.
// config/sage-orchestration-policy.json is the single source; this script is the
// only thing allowed to copy those numbers into C.
//
// The C side is deliberately given only the two hard ceilings: the domain budget
// (compute/repair/validate/plot) belongs to the server, and the native path
// receives it inside every result. The ceilings exist to survive a server bug,
// not to re-implement the policy.

import { mkdirSync, readFileSync, writeFileSync } from "fs";
import { dirname, resolve } from "path";
import { fileURLToPath } from "url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const SOURCE = resolve(ROOT, "config/sage-orchestration-policy.json");
const TARGET = resolve(ROOT, "generated/sage_orchestration_policy.h");

const REQUIRED = [
  "version",
  "maxComputeAttempts",
  "maxRepairAttempts",
  "maxValidationAttempts",
  "maxPlotAttempts",
  "maxPrematureFinalizations",
  "maxSameFailure",
  "maxWallClockMs",
  "maxTotalToolCalls",
  "hardMaxTotalCalls",
  "hardMaxWallClockMs",
];

const policy = JSON.parse(readFileSync(SOURCE, "utf8"));
for (const key of REQUIRED) {
  if (!Number.isInteger(policy[key])) {
    throw new Error(`${SOURCE}: '${key}' must be an integer, got ${policy[key]}`);
  }
}
if (policy.hardMaxTotalCalls <= policy.maxTotalToolCalls) {
  throw new Error(
    `${SOURCE}: hardMaxTotalCalls (${policy.hardMaxTotalCalls}) must exceed ` +
      `maxTotalToolCalls (${policy.maxTotalToolCalls}), otherwise the safety ceiling ` +
      "fires before the domain budget and the C path becomes the authority again"
  );
}
if (policy.hardMaxWallClockMs <= policy.maxWallClockMs) {
  throw new Error(
    `${SOURCE}: hardMaxWallClockMs (${policy.hardMaxWallClockMs}) must exceed ` +
      `maxWallClockMs (${policy.maxWallClockMs})`
  );
}

const header = `/* Generated by scripts/generate-sage-orchestration-policy.mjs — do not edit.
 * Source: config/sage-orchestration-policy.json
 *
 * Only the safety ceilings live here. The Sage domain budget is owned by
 * frontend/server/sageTurnTracker.mjs and travels inside every tool result; the
 * native path mirrors it and must never re-derive it. */
#ifndef DS4_SAGE_ORCHESTRATION_POLICY_H
#define DS4_SAGE_ORCHESTRATION_POLICY_H

#define DS4_SAGE_POLICY_VERSION ${policy.version}
#define DS4_SAGE_MAX_TOTAL_CALLS_HARD ${policy.hardMaxTotalCalls}
#define DS4_SAGE_MAX_WALL_CLOCK_HARD_MS ${policy.hardMaxWallClockMs}
#define DS4_SAGE_MAX_PREMATURE_FINALIZATIONS ${policy.maxPrematureFinalizations}

#endif /* DS4_SAGE_ORCHESTRATION_POLICY_H */
`;

mkdirSync(dirname(TARGET), { recursive: true });
writeFileSync(TARGET, header);
process.stdout.write(`generated ${TARGET}\n`);
