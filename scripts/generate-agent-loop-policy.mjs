#!/usr/bin/env node
// Generate generated/agent_loop_policy.h and generated/agent-loop-policy.json
// from the canonical policy JSON.
//
// C and Node each enforce the agent loop locally — the parser is not portable
// and porting it would be worse than two enforcement points.  What they must
// not do is disagree about the numbers, which is what happened when the native
// worker counted to 50 and AgentLoopGuard counted to its own constants.
// config/agent-loop-policy.json is the single source; this script is the only
// thing allowed to copy those numbers anywhere.

import { mkdirSync, readFileSync, writeFileSync } from "fs";
import { dirname, resolve } from "path";
import { fileURLToPath } from "url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const SOURCE = resolve(ROOT, "config/agent-loop-policy.json");
const HEADER = resolve(ROOT, "generated/agent_loop_policy.h");
const DESCRIPTOR = resolve(ROOT, "generated/agent-loop-policy.json");

// key -> C macro.  A key missing here is a key the C side cannot see, so the
// mapping is exhaustive by construction rather than by convention.
const MACROS = {
  schemaVersion: "DS4_AGENT_LOOP_POLICY_SCHEMA_VERSION",
  maxToolRoundsHard: "DS4_AGENT_MAX_TOOL_ROUNDS_HARD",
  protocolSameFailureStrategyChange:
    "DS4_AGENT_PROTOCOL_SAME_FAILURE_STRATEGY_CHANGE",
  protocolSameFailureTerminal: "DS4_AGENT_PROTOCOL_SAME_FAILURE_TERMINAL",
  protocolTotalFailureTerminal: "DS4_AGENT_PROTOCOL_TOTAL_FAILURE_TERMINAL",
  repeatedActionStrategyChange: "DS4_AGENT_REPEATED_ACTION_STRATEGY_CHANGE",
  repeatedActionTerminal: "DS4_AGENT_REPEATED_ACTION_TERMINAL",
  noProgressTerminal: "DS4_AGENT_NO_PROGRESS_TERMINAL",
  degenerateGenerationTerminal: "DS4_AGENT_DEGENERATE_GENERATION_TERMINAL",
  finalizationOnlyMaxModelRounds:
    "DS4_AGENT_FINALIZATION_ONLY_MAX_MODEL_ROUNDS",
};

export function validateAgentLoopPolicy(policy) {
  const keys = Object.keys(MACROS);
  for (const key of keys) {
    if (!Number.isInteger(policy[key])) {
      throw new Error(`'${key}' must be an integer, got ${policy[key]}`);
    }
    if (policy[key] <= 0) {
      throw new Error(`'${key}' must be > 0, got ${policy[key]}`);
    }
  }
  for (const key of Object.keys(policy)) {
    if (!keys.includes(key)) throw new Error(`unknown key '${key}'`);
  }

  // An escalation ladder whose rungs are out of order is not a ladder: a
  // strategy change that fires at or after the terminal threshold never fires.
  if (
    policy.protocolSameFailureStrategyChange >= policy.protocolSameFailureTerminal
  ) {
    throw new Error(
      "protocolSameFailureStrategyChange must be < protocolSameFailureTerminal",
    );
  }
  if (policy.repeatedActionStrategyChange >= policy.repeatedActionTerminal) {
    throw new Error(
      "repeatedActionStrategyChange must be < repeatedActionTerminal",
    );
  }
  if (policy.protocolSameFailureTerminal > policy.protocolTotalFailureTerminal) {
    throw new Error(
      "protocolSameFailureTerminal must be <= protocolTotalFailureTerminal",
    );
  }
  // The hard ceiling is a last resort, not the working limit: if it were lower
  // than a protocol threshold the protocol guard could never fire.
  if (policy.maxToolRoundsHard < policy.protocolTotalFailureTerminal) {
    throw new Error(
      "maxToolRoundsHard must be >= protocolTotalFailureTerminal",
    );
  }
  return policy;
}

export function renderAgentLoopPolicyHeader(policy) {
  const defines = Object.entries(MACROS)
    .map(([key, macro]) => `#define ${macro} ${policy[key]}`)
    .join("\n");
  return `/* Generated by scripts/generate-agent-loop-policy.mjs — do not edit.
 * Source: config/agent-loop-policy.json
 *
 * The native agent loop and the Node AgentLoopGuard enforce locally but share
 * this policy. A number that appears here must not be retyped anywhere else. */
#ifndef DS4_AGENT_LOOP_POLICY_H
#define DS4_AGENT_LOOP_POLICY_H

${defines}

#endif /* DS4_AGENT_LOOP_POLICY_H */
`;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const policy = validateAgentLoopPolicy(
    JSON.parse(readFileSync(SOURCE, "utf8")),
  );
  mkdirSync(dirname(HEADER), { recursive: true });
  writeFileSync(HEADER, renderAgentLoopPolicyHeader(policy));
  // The Node side reads the descriptor rather than config/ directly, so a stale
  // header and a fresh loader cannot coexist unnoticed.
  writeFileSync(DESCRIPTOR, `${JSON.stringify(policy, null, 2)}\n`);
  process.stdout.write(`generated ${HEADER}\ngenerated ${DESCRIPTOR}\n`);
}
